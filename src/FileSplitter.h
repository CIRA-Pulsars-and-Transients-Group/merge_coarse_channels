/*
 * FileSplitter.h
 *
 * Manages splitting of output filterbank files based on size or duration thresholds.
 */

#ifndef FILESPLITTER_H_
#define FILESPLITTER_H_

#include <cstdint>
#include <memory>
#include <string>
#include <vector>

class SigprocFile;

/**
 * Manages output file rotation based on size or time duration thresholds.
 * Handles creation of sequentially-numbered output files (e.g., output_0001.fil,
 * output_0002.fil, etc.) with proper SIGPROC headers.
 */
class FileSplitter {
public:
    /**
     * Constructor for FileSplitter.
     *
     * @param base_filename Base output filename (e.g., "output.fil").
     *                      The extension and base name are extracted for
     *                      constructing split filenames.
     * @param max_file_size_bytes Maximum file size in bytes (0 = no limit).
     * @param max_duration_seconds Maximum file duration in seconds (0.0 = no limit).
     *
     * Note: If both max_file_size_bytes and max_duration_seconds are non-zero,
     *       whichever threshold is reached first will trigger a split.
     */
    FileSplitter(const std::string& base_filename, uint64_t max_file_size_bytes = 0,
                 double max_duration_seconds = 0.0);

    ~FileSplitter();

    /**
     * Check if a split is needed based on current file state.
     *
     * @param current_bytes_written Bytes written to the current file.
     * @param current_duration Current file duration in seconds.
     * @return true if either size or duration limit has been exceeded, false otherwise.
     */
    bool NeedsSplit(uint64_t current_bytes_written, double current_duration) const;

    /**
     * Get the current output filename (with sequence number).
     *
     * @return Full filename for the current output file.
     */
    std::string GetCurrentFilename() const;

    /**
     * Get the filename for the next output file (after split).
     *
     * @return Full filename for the next output file.
     */
    std::string GetNextFilename() const;

    /**
     * Advance to the next file in the sequence.
     * Call this after closing the current file and before opening the next one.
     */
    void AdvanceToNextFile();

    /**
     * Get the current sequence number (1-indexed).
     *
     * @return Current file sequence number (starting at 1).
     */
    int GetCurrentSequence() const { return m_current_sequence; }

    /**
     * Get list of all created filenames.
     *
     * @return Vector of all filenames that have been generated by this splitter.
     */
    std::vector<std::string> GetCreatedFiles() const;

    /**
     * Reset the splitter state (for testing or reuse).
     */
    void Reset();

    /**
     * Check if splitting is enabled (either by size or duration).
     *
     * @return true if any split limit is set, false if no splitting is configured.
     */
    bool IsSplittingEnabled() const;

    /**
     * Get the base filename without extension.
     *
     * @return Base filename (e.g., "output" from "output.fil").
     */
    std::string GetBaseFilename() const { return m_base_filename_no_ext; }

    /**
     * Get the file extension (e.g., ".fil").
     *
     * @return File extension including the dot.
     */
    std::string GetExtension() const { return m_extension; }

private:
    std::string m_base_filename;              // Original filename as provided
    std::string m_base_filename_no_ext;       // Base name without extension
    std::string m_extension;                  // File extension (e.g., ".fil")
    uint64_t m_max_file_size;                 // Max file size in bytes (0 = no limit)
    double m_max_duration;                    // Max file duration in seconds (0.0 = no limit)
    int m_current_sequence;                   // Current file sequence number (1-indexed)
    std::vector<std::string> m_created_files; // List of all created filenames

    /**
     * Extract the base filename and extension from a full filename.
     *
     * @param filename Full filename to parse.
     * @param base_out Output: filename without extension.
     * @param ext_out Output: extension including the dot.
     */
    static void ParseFilename(const std::string& filename, std::string& base_out,
                              std::string& ext_out);

    /**
     * Generate a filename for a given sequence number.
     *
     * @param sequence Sequence number (1-indexed).
     * @return Formatted filename with sequence number.
     */
    std::string GenerateFilename(int sequence) const;
};

#endif /* FILESPLITTER_H_ */
